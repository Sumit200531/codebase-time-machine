import { useEffect, useRef } from "react";

/** About this project: problem, approach, and an honest account of what is real. */
export function About({ onClose }: { onClose: () => void }) {
  const ref = useRef<HTMLDialogElement>(null);
  useEffect(() => {
    const dialog = ref.current!;
    dialog.showModal();
    return () => dialog.close();
  }, []);
  return (
    <dialog ref={ref} className="about" onClose={onClose} aria-labelledby="about-title">
      <h2 id="about-title">See how software becomes software</h2>
      <p>
        Git history is chronological but not contextual. A log tells you what happened in which order, not how a codebase took shape. Codebase Time Machine turns that history into a temporal model you can move through: files are born, change, move and die; dependencies form; modules appear and settle into layers.
      </p>
      <h3>What is real here</h3>
      <p>
        Everything on screen is computed from Git history by the project's own pipeline: a hardened collector streams <code>git log</code>, a temporal engine replays every mainline commit, and a dependency analyzer resolves imports at each point in time. The reconstruction is verified against Git itself, file by file and line by line, on real repositories such as Express and Flask.
      </p>
      <p>
        TaskFlow is a synthetic project with fictional contributors, but its history is a real Git repository generated by a script and analyzed exactly like any other.
      </p>
      <h3>What is approximate</h3>
      <p>
        Imports are found lexically (pattern matching), not by a full parser. Architecture modules are inferred from directory structure. Search is keyword matching. A grounded AI Historian and GitHub import are planned and not part of this build.
      </p>
      <h3>Analyze your own repository</h3>
      <pre>npm run analyze -- path/to/repo --bundle repo.json</pre>
      <p>Then choose “Open bundle” and select the file. Nothing is uploaded; the bundle is read in your browser.</p>
      <form method="dialog">
        <button type="submit">Close</button>
      </form>
    </dialog>
  );
}
